function Suite = run_final_experiment_suite(mode)
%RUN_FINAL_EXPERIMENT_SUITE Execute the preregistered final experiment set.
% The suite contains no external algorithm baseline.  Every comparison shares
% the same observed-date replay, flight constraints, solver acceptance, and
% ForcedSafetyTrigger unless GuardOff is explicitly named.

    if nargin < 1 || isempty(mode), mode = 'run'; end
    mode = lower(string(mode));
    assert(any(mode == ["run", "reuse"]));
    outDir = 'results_frozen';
    if ~exist(outDir, 'dir'), mkdir(outDir); end

    cfg = systems_default_config();
    common = struct('InputSplit','holdout','UseSaoPauloJointReplay',true, ...
        'MILPTimeLimit',0.5,'ForcedSafetyEnabled',true, ...
        'RequireZeroUnsafeExecution',true,'FixedW3',20,'W3base',50, ...
        'W3MinRatio',.20,'PlanChangeScale',10, ...
        'EventWindThresholdMps',cfg.EmpiricalEventErrorThresholdMps, ...
        'EmpiricalEventErrorThresholdMps',cfg.EmpiricalEventErrorThresholdMps, ...
        'EnableWindTrigger',true,'EnableLowSoCTrigger',true);

    Suite = struct();
    Suite.ReleaseID = 'systems-sao-paulo-gfs-governance-final-r1';
    Suite.Protocol = protocol(common, cfg);
    Suite.Primary = runCase(outDir, 'primary_policy_comparison_60_scenarios.mat', ...
        60, 20268100, 'factorial5', common, mode);
    Suite.P80 = runCase(outDir, 'weather_p80_boundary_20_scenarios.mat', ...
        20, 20268200, 'gate2', merge(common, struct( ...
        'EventWindThresholdMps',1.1629470278, ...
        'EmpiricalEventErrorThresholdMps',1.1629470278)), mode);

    % Mechanism ablations: ordinary gates only. The shared execution guard
    % remains enabled, so these experiments cannot create a safety advantage
    % simply by permitting infeasible first-slot execution.
    Suite.WindGateOff = runCase(outDir, 'wind_gate_ablation_20_scenarios.mat', ...
        20, 20268300, 'gate2', merge(common, struct('EnableWindTrigger',false)), mode);
    Suite.LowSoCGateOff = runCase(outDir, 'low_soc_gate_ablation_20_scenarios.mat', ...
        20, 20268400, 'gate2', merge(common, struct('EnableLowSoCTrigger',false)), mode);

    % Plan-change-scale and inertia ranges are prespecified sensitivity
    % conditions, not a second selection procedure.
    Suite.W3Low = runCase(outDir, 'low_inertia_sensitivity_20_scenarios.mat', ...
        20, 20268500, 'factorial4', merge(common, struct('FixedW3',10, ...
        'W3base',20,'W3MinRatio',.50)), mode);
    Suite.W3Frozen = runCase(outDir, 'reference_inertia_sensitivity_20_scenarios.mat', ...
        20, 20268600, 'factorial4', common, mode);
    Suite.W3High = runCase(outDir, 'high_inertia_sensitivity_20_scenarios.mat', ...
        20, 20268700, 'factorial4', merge(common, struct('FixedW3',50, ...
        'W3base',50,'W3MinRatio',.50)), mode);
    Suite.ScaleLow = runCase(outDir, 'low_plan_change_scale_20_scenarios.mat', ...
        20, 20268800, 'gate2', merge(common, struct('PlanChangeScale',5)), mode);
    Suite.ScaleHigh = runCase(outDir, 'high_plan_change_scale_20_scenarios.mat', ...
        20, 20268900, 'gate2', merge(common, struct('PlanChangeScale',20)), mode);

    % The one planned operational-boundary analysis: rolling-window length.
    Suite.Window2 = runCase(outDir, 'planning_window_2_steps_20_scenarios.mat', ...
        20, 20269000, 'gate2', merge(common, struct('H',2)), mode);
    Suite.Window3 = runCase(outDir, 'planning_window_3_steps_20_scenarios.mat', ...
        20, 20269100, 'gate2', common, mode);
    Suite.Window4 = runCase(outDir, 'planning_window_4_steps_20_scenarios.mat', ...
        20, 20269200, 'gate2', merge(common, struct('H',4)), mode);

    Suite.GuardOn = runCase(outDir, 'safety_guard_on_20_scenarios.mat', ...
        20, 20269300, 'core2', common, mode);
    guardOff = merge(common, struct('ForcedSafetyEnabled',false, ...
        'RequireZeroUnsafeExecution',false));
    Suite.GuardOff = runCase(outDir, 'safety_guard_off_20_scenarios.mat', ...
        20, 20269300, 'core2', guardOff, mode);

    % Fleet-size boundary. D=2 retains capacity and priority UAV roles; D=3
    % is the primary configuration; D=4 adds a capacity UAV. The common
    % observed-date seeds and all governance/safety settings are unchanged.
    % These conditions test boundary transportability rather than reselecting
    % the primary operating point.
    fleetSeed = 20269400;
    Suite.Fleet2 = runCase(outDir, 'fleet_size_2_60_scenarios.mat', ...
        60, fleetSeed, 'gate2', merge(common, struct('D',2)), mode);
    Suite.Fleet3 = runCase(outDir, 'fleet_size_3_60_scenarios.mat', ...
        60, fleetSeed, 'gate2', merge(common, struct('D',3)), mode);
    Suite.Fleet4 = runCase(outDir, 'fleet_size_4_60_scenarios.mat', ...
        60, fleetSeed, 'gate2', merge(common, struct('D',4)), mode);
    save(fullfile(outDir, 'consolidated_experiment_suite.mat'), 'Suite', '-v7.3');
    writelines(string(Suite.Protocol), fullfile(outDir, 'EXPERIMENT_PROTOCOL.txt'));
    fprintf('SAO PAULO FINAL SUITE COMPLETE: %s\n', outDir);
end

function E = runCase(outDir, fileName, R, seedBase, policySet, override, mode)
    outFile = fullfile(outDir, fileName);
    if mode == "reuse" && exist(outFile, 'file') == 2
        S = load(outFile, 'Evidence'); E = S.Evidence;
    else
        E = run_governance_evidence_suite(R, [], outFile, seedBase, policySet, override);
    end
    assert(E.Summary.R == R && isequal(E.ScenarioSeeds, seedBase + (1:R)));
    if override.ForcedSafetyEnabled
        assert(all(E.Metrics.UnsafeExecutionRate(:) == 0), ...
            'Guarded run includes an infeasible execution.');
    end
    assert(all(E.Metrics.MaxConstraintViolation(:) <= ...
        E.Config.FeasibilityTolerance + 1e-12));
end

function c = merge(a,b)
    c = a; n = fieldnames(b);
    for k = 1:numel(n), c.(n{k}) = b.(n{k}); end
end

function lines = protocol(common, cfg)
    lines = [ ...
        "SAO PAULO GFS--ERA5 FINAL EXPERIMENT PROTOCOL"; ...
        "Primary: 60 paired observed-date replays; factorial five-policy architecture."; ...
        "Weather P90 normal-trigger threshold (development): " + string(cfg.EmpiricalEventErrorThresholdMps); ...
        "Fixed W3=20; adaptive W3 range=[10,50]; PlanChangeScale=10."; ...
        "All guarded policies share first-slot ForcedSafetyTrigger and deterministic fallback."; ...
        "Ablations disable one ordinary gate only; guard remains enabled."; ...
        "Sensitivity and window analyses are prespecified descriptive boundary evidence."; ...
        "Fleet boundary: D=2 capacity+priority; D=3 adds reserve; D=4 adds capacity; 60 paired replays each."; ...
        "No external algorithm baseline; no target-aircraft same-city energy claim." ...
    ];
end
